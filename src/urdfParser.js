// Universal URDF (Unified Robot Description Format) Parser & Exporter
// Works seamlessly in both Node.js (test/server) and Browser environments.

import { DEFAULT_TOOL_OFFSET_RPY, TOOL_TYPES, normalizeModelStyle, resolveJointModelStyle } from './kinematics.js';

const DEG2RAD = Math.PI / 180;
const RAD2DEG = 180 / Math.PI;

function round(val, decimals = 4) {
  return Number(Math.round(val + 'e' + decimals) + 'e-' + decimals);
}

/**
 * Exports a serial robot DH joint configuration to a standard ROS URDF XML string.
 * @param {Array} joints - Normalized DH joint array
 * @param {string} robotName - Name of the robot
 * @param {Object} toolConfig - Active end-effector tool ({ toolType, toolOffsetRpy })
 * @returns {string} URDF XML string
 */
export function exportToURDF(joints, robotName = 'DH_Robot', toolConfig = {}) {
  if (!Array.isArray(joints) || joints.length === 0) {
    throw new Error('Nenhuma junta fornecida para exportação URDF.');
  }

  const spec = TOOL_TYPES[toolConfig?.toolType] || TOOL_TYPES.gripper;
  const hasModelStyle = Boolean(toolConfig?.modelStyle && typeof toolConfig.modelStyle === 'object');
  const style = normalizeModelStyle(toolConfig?.modelStyle);
  const offsetRpy = Array.isArray(toolConfig?.toolOffsetRpy) && toolConfig.toolOffsetRpy.length === 3
    ? toolConfig.toolOffsetRpy.map(v => (Number.isFinite(Number(v)) ? round(Number(v), 2) : 0))
    : [...DEFAULT_TOOL_OFFSET_RPY];
  const offsetRpyRad = offsetRpy.map(v => round(v * DEG2RAD));

  const cleanName = robotName.replace(/[^a-zA-Z0-9_-]/g, '_').toLowerCase() || 'dh_robot';
  let xml = `<?xml version="1.0" encoding="utf-8"?>\n`;
  xml += `<!-- Generated by DH Robot Kinematics Platform -->\n`;
  xml += `<robot name="${cleanName}">\n\n`;

  // Material definitions for rich visualization in RViz / WebGL
  xml += `  <material name="pedestal_mat">\n    <color rgba="0.2 0.25 0.32 1.0"/>\n  </material>\n`;
  xml += `  <material name="link_accent">\n    <color rgba="0.23 0.51 0.96 1.0"/>\n  </material>\n`;
  xml += `  <material name="motor_mat">\n    <color rgba="0.93 0.28 0.6 1.0"/>\n  </material>\n`;
  xml += `  <material name="tool_gold">\n    <color rgba="0.96 0.77 0.19 1.0"/>\n  </material>\n\n`;

  // Base link (pedestal)
  xml += `  <link name="base_link">\n`;
  if (hasModelStyle) {
    const baseParts = [
      `link_shape="${style.linkShape}"`,
      `link_radius="${round(style.linkRadius)}"`,
      `rev_radius="${round(style.revRadius)}"`,
      `rev_length="${round(style.revLength)}"`,
      `prism_width="${round(style.prismWidth)}"`,
      `prism_length="${round(style.prismLength)}"`,
    ];
    if (style.revColor) baseParts.push(`rev_color="${style.revColor}"`);
    if (style.prismColor) baseParts.push(`prism_color="${style.prismColor}"`);
    if (style.linkColor) baseParts.push(`link_color="${style.linkColor}"`);
    const baseAttrs = baseParts.join(' ');
    const perEntries = style.perJoint ? Object.entries(style.perJoint) : [];
    if (perEntries.length === 0) {
      xml += `    <model_style ${baseAttrs}/>\n`;
    } else {
      xml += `    <model_style ${baseAttrs}>\n`;
      for (const [jid, ov] of perEntries) {
        const attrs = [`id="${jid}"`];
        if (ov.linkShape) attrs.push(`link_shape="${ov.linkShape}"`);
        if (ov.linkRadius !== undefined) attrs.push(`link_radius="${round(ov.linkRadius)}"`);
        if (ov.revRadius !== undefined) attrs.push(`rev_radius="${round(ov.revRadius)}"`);
        if (ov.revLength !== undefined) attrs.push(`rev_length="${round(ov.revLength)}"`);
        if (ov.prismWidth !== undefined) attrs.push(`prism_width="${round(ov.prismWidth)}"`);
        if (ov.prismLength !== undefined) attrs.push(`prism_length="${round(ov.prismLength)}"`);
        if (ov.jointColor) attrs.push(`joint_color="${ov.jointColor}"`);
        if (ov.linkColor) attrs.push(`link_color="${ov.linkColor}"`);
        xml += `      <joint_style ${attrs.join(' ')}/>\n`;
      }
      xml += `    </model_style>\n`;
    }
  }
  xml += `    <visual>\n`;
  xml += `      <origin xyz="0 0 0.1" rpy="0 0 0"/>\n`;
  xml += `      <geometry>\n        <cylinder radius="0.35" length="0.2"/>\n      </geometry>\n`;
  xml += `      <material name="pedestal_mat"/>\n`;
  xml += `    </visual>\n`;
  xml += `    <collision>\n`;
  xml += `      <origin xyz="0 0 0.1" rpy="0 0 0"/>\n`;
  xml += `      <geometry>\n        <cylinder radius="0.35" length="0.2"/>\n      </geometry>\n`;
  xml += `    </collision>\n`;
  xml += `  </link>\n\n`;

  let prevLink = 'base_link';

  joints.forEach((joint, idx) => {
    const jointNum = idx + 1;
    const jointName = `joint_${jointNum}`;
    const linkName = `link_${jointNum}`;
    const isRevolute = joint.type === 'R';
    const urdfType = isRevolute ? 'revolute' : 'prismatic';

    // In serial DH, translation along Z is d, translation along X is a, twist along X is alpha
    // Origin of this joint relative to the previous link
    const x = round(joint.a ?? 0);
    const z = round(joint.d ?? 0);
    const alphaRad = round((joint.alpha ?? 0) * DEG2RAD);

    // Axis is always Z (0 0 1) in standard DH convention
    const axisX = 0;
    const axisY = 0;
    const axisZ = 1;

    // Limits in standard units: rad for revolute, meters/units for prismatic
    const lower = isRevolute ? round((joint.min ?? -180) * DEG2RAD) : round(joint.min ?? 0);
    const upper = isRevolute ? round((joint.max ?? 180) * DEG2RAD) : round(joint.max ?? 10);
    const velocity = isRevolute
      ? round((joint.speed && joint.speed > 0 ? joint.speed : 180) * DEG2RAD)
      : round(joint.speed && joint.speed > 0 ? joint.speed : 2.0);

    xml += `  <!-- Joint ${jointNum} (${joint.type}) -->\n`;
    xml += `  <joint name="${jointName}" type="${urdfType}">\n`;
    xml += `    <parent link="${prevLink}"/>\n`;
    xml += `    <child link="${linkName}"/>\n`;
    xml += `    <origin xyz="${x} 0 ${z}" rpy="${alphaRad} 0 0"/>\n`;
    xml += `    <axis xyz="${axisX} ${axisY} ${axisZ}"/>\n`;
    xml += `    <limit lower="${lower}" upper="${upper}" effort="150.0" velocity="${velocity}"/>\n`;
    xml += `  </joint>\n\n`;

    // Link representation
    const linkLength = Math.max(0.2, Math.sqrt(x * x + z * z));
    const jStyle = resolveJointModelStyle(style, joint.id ?? jointNum);
    const linkGeomXml = jStyle.linkShape === 'square'
      ? `<box size="${round(jStyle.linkRadius * 2)} ${round(jStyle.linkRadius * 2)} ${round(linkLength)}"/>`
      : jStyle.linkShape === 'flat'
        ? `<box size="${round(jStyle.linkRadius * 2.4)} ${round(jStyle.linkRadius * 1.1)} ${round(linkLength)}"/>`
        : `<cylinder radius="${hasModelStyle ? round(jStyle.linkRadius) : 0.08}" length="${round(linkLength)}"/>`;
    xml += `  <link name="${linkName}">\n`;
    xml += `    <visual>\n`;
    xml += `      <origin xyz="${round(x / 2)} 0 ${round(z / 2)}" rpy="0 0 0"/>\n`;
    xml += `      <geometry>\n        ${linkGeomXml}\n      </geometry>\n`;
    xml += `      <material name="link_accent"/>\n`;
    xml += `    </visual>\n`;
    xml += `    <collision>\n`;
    xml += `      <origin xyz="${round(x / 2)} 0 ${round(z / 2)}" rpy="0 0 0"/>\n`;
    xml += `      <geometry>\n        ${linkGeomXml}\n      </geometry>\n`;
    xml += `    </collision>\n`;
    xml += `  </link>\n\n`;

    prevLink = linkName;
  });

  // End-effector tool attachment + TCP link
  xml += `  <!-- Tool0 / End-Effector (${spec.shortLabel}) -->\n`;
  xml += `  <link name="tool0">\n`;
  xml += `    <tool_config type="${spec.id}" offset_rpy="${offsetRpy.join(' ')}"/>\n`;
  xml += `    <visual>\n`;
  xml += `      <origin xyz="${round(spec.length / 2)} 0 0" rpy="0 0 0"/>\n`;
  xml += `      <geometry>\n        <cylinder radius="${round(spec.radius / 2)}" length="${round(spec.length)}"/>\n      </geometry>\n`;
  xml += `      <material name="tool_gold"/>\n`;
  xml += `    </visual>\n`;
  xml += `  </link>\n\n`;
  xml += `  <joint name="joint_ee_fixed" type="fixed">\n`;
  xml += `    <parent link="${prevLink}"/>\n`;
  xml += `    <child link="tool0"/>\n`;
  xml += `    <origin xyz="0 0 0" rpy="${offsetRpyRad.join(' ')}"/>\n`;
  xml += `  </joint>\n\n`;
  xml += `  <link name="tcp_link"/>\n`;
  xml += `  <joint name="joint_tcp_fixed" type="fixed">\n`;
  xml += `    <parent link="tool0"/>\n`;
  xml += `    <child link="tcp_link"/>\n`;
  xml += `    <origin xyz="${round(spec.length)} 0 0" rpy="0 0 0"/>\n`;
  xml += `  </joint>\n\n`;

  xml += `</robot>\n`;
  return xml;
}

/**
 * Universal XML tag value extractor using regex for platform portability
 */
function extractAttr(tagString, attrName) {
  const match = new RegExp(`${attrName}\\s*=\\s*["']([^"']*)["']`, 'i').exec(tagString);
  return match ? match[1] : null;
}

/**
 * Parses a standard URDF XML string into normalized DH joints.
 * @param {string} urdfString - URDF XML content
 * @returns {Array} Array of DH joints
 */
export function parseURDF(urdfString) {
  if (typeof urdfString !== 'string' || !urdfString.trim()) {
    throw new Error('Arquivo URDF vazio ou inválido.');
  }

  if (!/<robot[\s\S]*?>[\s\S]*<\/robot>/i.test(urdfString)) {
    throw new Error('Formato URDF inválido: tag <robot> não encontrada.');
  }

  let parsedToolType = null;
  let parsedOffsetRpy = [0, 0, 0];
  let parsedModelStyle = null;
  const toolConfigMatch = /<tool_config\b([\s\S]*?)\/?>/i.exec(urdfString);
  if (toolConfigMatch) {
    const tAttr = extractAttr(toolConfigMatch[1], 'type');
    if (tAttr && TOOL_TYPES[tAttr]) parsedToolType = tAttr;
    const offAttr = extractAttr(toolConfigMatch[1], 'offset_rpy');
    if (offAttr) {
      const nums = offAttr.trim().split(/\s+/).map(Number);
      if (nums.length === 3 && nums.every(Number.isFinite)) parsedOffsetRpy = nums;
    }
  }
  const modelStyleMatch = /<model_style\b([^>]*)>/i.exec(urdfString);
  if (modelStyleMatch) {
    const perJoint = {};
    const jointStyleRegex = /<joint_style\b([^>]*?)\/?>/gi;
    let jsMatch;
    while ((jsMatch = jointStyleRegex.exec(urdfString)) !== null) {
      const attrsStr = jsMatch[1];
      const idAttr = extractAttr(attrsStr, 'id');
      if (!idAttr || !/^\d+$/.test(idAttr)) continue;
      perJoint[idAttr] = {
        ...(extractAttr(attrsStr, 'link_shape') ? { linkShape: extractAttr(attrsStr, 'link_shape') } : {}),
        ...(extractAttr(attrsStr, 'link_radius') !== null ? { linkRadius: extractAttr(attrsStr, 'link_radius') } : {}),
        ...(extractAttr(attrsStr, 'rev_radius') !== null ? { revRadius: extractAttr(attrsStr, 'rev_radius') } : {}),
        ...(extractAttr(attrsStr, 'rev_length') !== null ? { revLength: extractAttr(attrsStr, 'rev_length') } : {}),
        ...(extractAttr(attrsStr, 'prism_width') !== null ? { prismWidth: extractAttr(attrsStr, 'prism_width') } : {}),
        ...(extractAttr(attrsStr, 'prism_length') !== null ? { prismLength: extractAttr(attrsStr, 'prism_length') } : {}),
        ...(extractAttr(attrsStr, 'joint_color') ? { jointColor: extractAttr(attrsStr, 'joint_color') } : {}),
        ...(extractAttr(attrsStr, 'link_color') ? { linkColor: extractAttr(attrsStr, 'link_color') } : {}),
      };
    }
    parsedModelStyle = normalizeModelStyle({
      linkShape: extractAttr(modelStyleMatch[1], 'link_shape'),
      linkRadius: extractAttr(modelStyleMatch[1], 'link_radius'),
      revRadius: extractAttr(modelStyleMatch[1], 'rev_radius'),
      revLength: extractAttr(modelStyleMatch[1], 'rev_length'),
      prismWidth: extractAttr(modelStyleMatch[1], 'prism_width'),
      prismLength: extractAttr(modelStyleMatch[1], 'prism_length'),
      revColor: extractAttr(modelStyleMatch[1], 'rev_color'),
      prismColor: extractAttr(modelStyleMatch[1], 'prism_color'),
      linkColor: extractAttr(modelStyleMatch[1], 'link_color'),
      perJoint,
    });
  }

  // Extract all <joint> blocks
  const jointRegex = /<joint\b([\s\S]*?)>([\s\S]*?)<\/joint>/gi;
  const parsedJoints = [];
  let match;

  while ((match = jointRegex.exec(urdfString)) !== null) {
    const jointHeader = match[1];
    const jointBody = match[2];

    const name = extractAttr(jointHeader, 'name') || `joint_${parsedJoints.length + 1}`;
    const typeStr = (extractAttr(jointHeader, 'type') || 'revolute').toLowerCase();

    if (name === 'joint_ee_fixed' && !toolConfigMatch) {
      const eeOriginMatch = /<origin\b([\s\S]*?)\/?>/i.exec(jointBody);
      if (eeOriginMatch) {
        const eeRpyStr = extractAttr(eeOriginMatch[1], 'rpy');
        if (eeRpyStr) {
          const rads = eeRpyStr.trim().split(/\s+/).map(Number);
          if (rads.length === 3 && rads.every(Number.isFinite)) {
            parsedOffsetRpy = rads.map(v => round(v * RAD2DEG, 2));
          }
        }
      }
    }

    // Skip fixed joints like base-to-world or end-effector
    if (typeStr === 'fixed' || name.toLowerCase().includes('fixed') || name.toLowerCase().includes('tool')) {
      continue;
    }

    const type = typeStr === 'prismatic' ? 'P' : 'R';

    // Parse <origin xyz="..." rpy="..."/>
    const originMatch = /<origin\b([\s\S]*?)\/?>/i.exec(jointBody);
    let xyz = [0, 0, 0];
    let rpy = [0, 0, 0];
    if (originMatch) {
      const xyzStr = extractAttr(originMatch[1], 'xyz');
      const rpyStr = extractAttr(originMatch[1], 'rpy');
      if (xyzStr) xyz = xyzStr.trim().split(/\s+/).map(Number);
      if (rpyStr) rpy = rpyStr.trim().split(/\s+/).map(Number);
    }

    // In standard DH:
    // a is length along X, d is offset along Z, alpha is rotation along X in degrees
    const a = round(xyz[0] || 0, 2);
    const d = round(xyz[2] || 0, 2);
    const alpha = round((rpy[0] || 0) * RAD2DEG, 2);

    // Parse <limit lower="..." upper="..." velocity="..."/>
    const limitMatch = /<limit\b([\s\S]*?)\/?>/i.exec(jointBody);
    let lower = type === 'R' ? -180 : 0;
    let upper = type === 'R' ? 180 : 10;
    let speed = 0;

    if (limitMatch) {
      const lowerAttr = extractAttr(limitMatch[1], 'lower');
      const upperAttr = extractAttr(limitMatch[1], 'upper');
      const velAttr = extractAttr(limitMatch[1], 'velocity');

      if (lowerAttr !== null && !isNaN(Number(lowerAttr))) {
        lower = type === 'R' ? round(Number(lowerAttr) * RAD2DEG, 1) : round(Number(lowerAttr), 2);
      }
      if (upperAttr !== null && !isNaN(Number(upperAttr))) {
        upper = type === 'R' ? round(Number(upperAttr) * RAD2DEG, 1) : round(Number(upperAttr), 2);
      }
      if (velAttr !== null && !isNaN(Number(velAttr))) {
        speed = type === 'R' ? round(Number(velAttr) * RAD2DEG, 1) : round(Number(velAttr), 2);
      }
    }

    const defaultVal = type === 'R' ? 0 : Math.max(0, d);

    parsedJoints.push({
      id: parsedJoints.length + 1,
      type,
      a,
      alpha,
      theta: type === 'R' ? defaultVal : 0,
      d: type === 'P' ? defaultVal : d,
      val: defaultVal,
      min: lower,
      max: upper,
      speed,
    });
  }

  if (parsedJoints.length === 0) {
    throw new Error('Nenhuma junta móvel (revolute/prismatic) encontrada no arquivo URDF.');
  }

  if (parsedToolType || parsedOffsetRpy.some(v => Math.abs(v) > 1e-6) || parsedModelStyle) {
    const toolCfgValue = {
      toolType: parsedToolType || 'gripper',
      toolOffsetRpy: parsedOffsetRpy,
    };
    if (parsedModelStyle) toolCfgValue.modelStyle = parsedModelStyle;
    Object.defineProperty(parsedJoints, 'toolConfig', {
      value: toolCfgValue,
      enumerable: false,
      configurable: true,
    });
  }

  return parsedJoints;
}
